import type { Pt } from '../util/noise';

export type PieceType = 'p' | 'n' | 'b' | 'r' | 'q' | 'k';
export type Color = 'w' | 'b';

export interface Detail {
  pts: Pt[];
  w: number; // 선 두께(칸 단위)
  fill?: boolean;
}
export interface PieceGeom {
  polys: Pt[][];
  details: Detail[];
  baseHalf: number;
  height: number;
}

type Prof = [number, number][]; // [y, r]

function ball(cy: number, R: number, fromDeg: number): Prof {
  const out: Prof = [];
  for (let a = fromDeg; a <= 90; a += 7.5) {
    const t = (a * Math.PI) / 180;
    out.push([cy + R * Math.sin(t), R * Math.cos(t)]);
  }
  out[out.length - 1][1] = 0;
  return out;
}

function circle(cx: number, cy: number, R: number, n = 22): Pt[] {
  const out: Pt[] = [];
  for (let i = 0; i < n; i++) {
    const t = (i / n) * Math.PI * 2;
    out.push([cx + R * Math.cos(t), cy + R * Math.sin(t)]);
  }
  return out;
}

/** 반쪽 윤곽선을 좌우로 붙여 닫힌 다각형 생성. top은 오른쪽→왼쪽 순서 */
function lathe(prof: Prof, top: Pt[] = []): Pt[] {
  const right: Pt[] = prof.map(([y, r]) => [r, y]);
  const left: Pt[] = prof
    .slice()
    .reverse()
    .filter(([, r]) => r > 0)
    .map(([y, r]) => [-r, y]);
  return [...right, ...top, ...left];
}

